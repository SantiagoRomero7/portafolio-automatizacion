/** Cuántas veces más rápido; null cuando el después no requiere a nadie */
export function factor(a: Automation): number | null {
  return a.afterMin > 0 ? a.beforeMin / a.afterMin : null
}

export function sumBefore(list: Automation[]) {
  return list.reduce((acc, a) => acc + a.beforeMin, 0)
}

export function sumAfter(list: Automation[]) {
  return list.reduce((acc, a) => acc + a.afterMin, 0)
}

